-- Reserved Lightning addresses.
-- The seed is the same list as src/db/reservedUsernames.ts. The app checks
-- that file; these triggers are the database backstop. Existing rows are
-- left in place: the trigger skips an UPDATE that does not change username,
-- and the length/format checks skip the existing-row scan so a short legacy name does
-- not stop this migration.
CREATE TABLE IF NOT EXISTS "reserved_usernames" (
	"name" text NOT NULL,
	"category" text NOT NULL,
	"match" text NOT NULL,
	"assigned_nostr_pubkey" text,
	CONSTRAINT "reserved_usernames_name_match_pk" PRIMARY KEY("name","match"),
	CONSTRAINT "reserved_usernames_category" CHECK (category IN ('hard', 'assignable')),
	CONSTRAINT "reserved_usernames_match" CHECK (match IN ('exact', 'prefix', 'contains')),
	CONSTRAINT "reserved_usernames_assignment" CHECK (category = 'assignable' OR assigned_nostr_pubkey IS NULL)
);
