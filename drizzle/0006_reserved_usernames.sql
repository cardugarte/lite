CREATE OR REPLACE FUNCTION reject_reserved_username()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  normalized text;
BEGIN
  IF TG_OP = 'UPDATE' AND OLD.username IS NOT DISTINCT FROM NEW.username THEN
    RETURN NEW;
  END IF;

  normalized := translate(lower(btrim(NEW.username)), '.-_', '');

  IF normalized ~ '^npub1' OR normalized ~ '^nsec1' OR normalized ~ '^[0-9a-f]{64}$' THEN
    RAISE EXCEPTION 'not available' USING ERRCODE = '23514';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM reserved_usernames r
    WHERE (
      (r.match = 'exact' AND r.name = normalized)
      OR (r.match = 'prefix' AND left(normalized, char_length(r.name)) = r.name)
      OR (r.match = 'contains' AND strpos(normalized, r.name) > 0)
    )
    AND NOT (
      r.category = 'assignable'
      AND r.assigned_nostr_pubkey IS NOT NULL
      AND r.assigned_nostr_pubkey = NEW.nostr_pubkey
    )
  ) THEN
    RAISE EXCEPTION 'not available' USING ERRCODE = '23514';
  END IF;

  RETURN NEW;
END;
$$;
